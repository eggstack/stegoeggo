/// Main pipeline for applying protection to images.
///
/// Coordinates between different protector implementations based on the
/// selected protection level. Create one via [`ProtectionPipeline::new`]
/// or use the convenience functions ([`process_image`], [`process_image_bytes`]).
#[non_exhaustive]
pub struct ProtectionPipeline {}

impl Clone for ProtectionPipeline {
    fn clone(&self) -> Self {
        Self::new()
    }
}

impl ProtectionPipeline {
    /// Create a new ProtectionPipeline with default protectors.
    pub fn new() -> Self {
        Self {}
    }

    fn validate_dimensions(img: &DynamicImage, max_dim: Option<u32>) -> Result<()> {
        if let Some(max) = max_dim {
            let (width, height) = img.dimensions();
            if width > max || height > max {
                return Err(Error::ImageDecode(format!(
                    "Image dimensions {}x{} exceed maximum allowed {}",
                    width, height, max
                )));
            }
        }
        Ok(())
    }

    /// Process an image with the specified protection level.
    ///
    /// Delegates to the canonical request/plan execution path used by the
    /// top-level [`process_image`] function. `Disabled` short-circuits to a
    /// borrowed no-op passthrough.
    pub fn process<'a>(
        &'a self,
        img: &'a DynamicImage,
        level: ProtectionLevel,
        ctx: &ProtectionContext,
    ) -> Result<Cow<'a, DynamicImage>> {
        Self::validate_dimensions(img, ctx.max_dimension())?;

        if level == ProtectionLevel::Disabled {
            return Ok(Cow::Borrowed(img));
        }

        Ok(Cow::Owned(process_image_ref(img, level, ctx)?))
    }

    /// Process image bytes with the specified protection level.
    ///
    /// Delegates to the canonical [`process_image_bytes`] entry point so
    /// `ProtectionPipeline::process_bytes` and the top-level byte API
    /// produce identical results for the same `(level, ctx)` inputs.
    pub fn process_bytes(
        &self,
        img_bytes: &[u8],
        level: ProtectionLevel,
        ctx: &ProtectionContext,
    ) -> Result<Vec<u8>> {
        if level == ProtectionLevel::Disabled {
            return Ok(img_bytes.to_vec());
        }
        process_image_bytes(img_bytes, level, ctx)
    }
}

impl Default for ProtectionPipeline {
    fn default() -> Self {
        Self::new()
    }
}

/// Process an image with the specified protection level.
///
/// Takes an owned DynamicImage and returns a processed image.
///
/// # Errors
///
/// Returns [`Error::ImageDecode`] if the image dimensions exceed `max_dimension`.
/// Returns [`Error::ImageEncode`] or [`Error::Steganography`] if encoding or
/// embedding fails.
#[must_use = "the protected image should be saved or used"]
pub fn process_image(
    img: DynamicImage,
    level: ProtectionLevel,
    ctx: &ProtectionContext,
) -> Result<DynamicImage> {
    if level == ProtectionLevel::Disabled {
        return Ok(img);
    }
    process_image_ref(&img, level, ctx)
}

fn process_image_ref(
    img: &DynamicImage,
    level: ProtectionLevel,
    ctx: &ProtectionContext,
) -> Result<DynamicImage> {
    ctx.validate()?;
    ProtectionPipeline::validate_dimensions(img, ctx.max_dimension())?;
    if level == ProtectionLevel::Disabled {
        return Ok(img.clone());
    }
    let request = request_from_legacy(level, ctx);
    let format = ctx
        .output_format()
        .or_else(|| ctx.input_format())
        .unwrap_or(crate::types::DEFAULT_OUTPUT_FORMAT);
    let plan = resolve_request(&request, format)?;
    let steganography = SteganographyProtector::new();

    match plan.channels().hidden_marker {
        HiddenMarkerMode::Disabled => Ok(img.clone()),
        HiddenMarkerMode::SeedOnly => {
            if plan.output_format() == crate::types::ImageOutputFormat::Jpeg {
                let jpeg_bytes = crate::util::image::encode_image_with_options(
                    img,
                    Some(plan.output_format()),
                    plan.processing().progressive_jpeg,
                    plan.processing().jpeg_quality,
                )?;
                let with_seed = steganography.apply_qtable_seed_bytes(&jpeg_bytes, plan.seed())?;
                return image::load_from_memory(&with_seed)
                    .map_err(|e| Error::ImageDecode(e.to_string()));
            }

            let mut rgba = img.to_rgba8();
            SteganographyProtector::embed_seed_lsb_fallback_pub(&mut rgba, plan.seed());
            Ok(DynamicImage::ImageRgba8(rgba))
        }
        HiddenMarkerMode::BestEffort => {
            if plan.output_format() == crate::types::ImageOutputFormat::Jpeg {
                let jpeg_bytes = crate::util::image::encode_image_with_options(
                    img,
                    Some(plan.output_format()),
                    plan.processing().progressive_jpeg,
                    plan.processing().jpeg_quality,
                )?;
                let with_stego =
                    steganography.apply_dct_stego_bytes_from_plan(&jpeg_bytes, &plan, None)?;
                let (output, _) = with_stego.into_parts();
                return image::load_from_memory(&output)
                    .map_err(|e| Error::ImageDecode(e.to_string()));
            }
            let (processed, _summary) =
                steganography.apply_lsb_to_image_with_summary_from_plan(img, &plan, None)?;
            Ok(processed)
        }
        HiddenMarkerMode::Tiled { tile_size } => {
            if plan.output_format() == crate::types::ImageOutputFormat::Jpeg {
                let jpeg_bytes = crate::util::image::encode_image_with_options(
                    img,
                    Some(plan.output_format()),
                    plan.processing().progressive_jpeg,
                    plan.processing().jpeg_quality,
                )?;
                let with_stego = steganography.apply_dct_stego_bytes_from_plan(
                    &jpeg_bytes,
                    &plan,
                    Some(tile_size),
                )?;
                let (output, _) = with_stego.into_parts();
                return image::load_from_memory(&output)
                    .map_err(|e| Error::ImageDecode(e.to_string()));
            }
            let (processed, _summary) = steganography.apply_lsb_to_image_with_summary_from_plan(
                img,
                &plan,
                Some(tile_size),
            )?;
            Ok(processed)
        }
    }
}

/// Process multiple images in parallel.
///
/// Takes a slice of images and returns a vector of processed images.
/// Uses Rayon for parallel processing.
///
/// # Examples
///
/// ```no_run
/// use stegoeggo::{process_images_parallel, ProtectionContext, ProtectionLevel};
/// use image::DynamicImage;
///
/// let images: Vec<DynamicImage> = vec![
///     image::open("image1.png").unwrap(),
///     image::open("image2.png").unwrap(),
/// ];
/// let ctx = ProtectionContext::new(0.5, 42);
/// let protected = process_images_parallel(&images, ProtectionLevel::Standard, &ctx).unwrap();
/// ```
///
/// # Errors
///
/// Returns the first error encountered from any image processing call.
#[cfg(feature = "parallel")]
#[cfg_attr(docsrs, doc(cfg(feature = "parallel")))]
#[must_use = "the protected images should be saved or used"]
pub fn process_images_parallel(
    images: &[DynamicImage],
    level: ProtectionLevel,
    ctx: &ProtectionContext,
) -> Result<Vec<DynamicImage>> {
    use rayon::prelude::*;
    images
        .par_iter()
        .map(|img| process_image(img.clone(), level, ctx))
        .collect()
}

