/// Resolve a [`ProtectionRequest`] into an immutable execution plan.
///
/// This validates all input combinations and produces an execution plan
/// that pipeline stages consume. Resolution runs once before any image
/// processing occurs.
pub fn resolve_request(
    request: &ProtectionRequest,
    input_format: ImageOutputFormat,
) -> Result<ResolvedProtectionPlan> {
    protected::resolve::resolve_request(request, input_format)
}

fn request_from_legacy(level: ProtectionLevel, ctx: &ProtectionContext) -> ProtectionRequest {
    let rights_metadata = ctx.effective_metadata_injection();

    let channels = match level {
        ProtectionLevel::Disabled => ProtectionChannels {
            rights_metadata: false,
            hidden_marker: HiddenMarkerMode::Disabled,
            authentication: AuthenticationMode::None,
        },
        ProtectionLevel::Light | ProtectionLevel::Standard => {
            let authentication = if ctx.mac_key().is_some() {
                AuthenticationMode::Hmac
            } else {
                AuthenticationMode::None
            };
            let hidden_marker = match level {
                ProtectionLevel::Light => HiddenMarkerMode::SeedOnly,
                ProtectionLevel::Standard => ctx
                    .tile_size()
                    .filter(|&s| s > 0)
                    .map_or(HiddenMarkerMode::BestEffort, |tile_size| {
                        HiddenMarkerMode::Tiled { tile_size }
                    }),
                ProtectionLevel::Disabled => {
                    debug_assert!(
                        false,
                        "Disabled is handled by the outer match; unreachable here"
                    );
                    HiddenMarkerMode::SeedOnly
                }
            };
            ProtectionChannels {
                rights_metadata,
                hidden_marker,
                authentication,
            }
        }
    };

    let policy = if !rights_metadata {
        RightsPolicy::Unspecified
    } else {
        ctx.dmi_value()
            .map(RightsPolicy::from)
            .unwrap_or_else(|| level.default_policy())
    };

    let mut notice = RightsNotice::default();
    let effective_dmi = ctx.dmi_value().unwrap_or_else(|| DmiValue::from(policy));
    notice = notice.with_dmi(effective_dmi);
    notice = notice.with_seed(ctx.seed());

    let legal_claims_decision = legal_claims_decision(ctx);

    let output_format = ctx.output_format();
    let mut request = ProtectionRequest::new(notice, policy, channels)
        .with_seed(ctx.seed())
        .with_intensity(ctx.intensity())
        .with_jpeg_quality(ctx.jpeg_quality());

    if let Some(fmt) = output_format {
        request = request.with_output_format(fmt);
    }
    if ctx.progressive_jpeg() {
        request = request.with_progressive_jpeg();
    }
    if legal_claims_decision == LegalClaimsDecision::Include {
        if let Some(meta) = ctx.legal_metadata() {
            request = request.with_legal_metadata(meta.clone());
        }
    }
    if let Some(key) = ctx.mac_key() {
        request = request.with_mac_key(key.to_vec());
    }
    request = request.with_resource_limits(ctx.resource_limits());

    let mut processing = request.processing().clone();
    if let Some(max_dim) = ctx.max_dimension() {
        processing.max_dimension = Some(max_dim);
    }
    processing.metadata_update_policy = ctx.metadata_update_policy();
    if let Some(r) = ctx.stego_redundancy_field() {
        processing.stego_redundancy = Some(r);
    }
    if let Some(hash) = ctx.content_hash() {
        processing.content_hash = Some(hash);
    }
    if let Some(ts) = ctx.timestamp_override() {
        processing.timestamp_override = Some(ts.to_string());
    }
    request = request.with_processing(processing);

    request
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum LegalClaimsDecision {
    Include,
    Exclude,
}

fn legal_claims_decision(ctx: &ProtectionContext) -> LegalClaimsDecision {
    match ctx.inject_legal_claims() {
        Some(false) => LegalClaimsDecision::Exclude,
        Some(true) | None => LegalClaimsDecision::Include,
    }
}

/// Process image bytes with the specified protection level.
///
/// Automatically detects the input format from magic bytes and preserves
/// the output format. Returns the protected image as bytes. `Disabled`
/// protection is a byte-for-byte no-op and does not require format detection.
///
/// For JPEG-in/JPEG-out, this function takes a byte-only fast path that
/// operates on DCT coefficients directly, avoiding pixel decode/encode cycles.
///
/// # Examples
///
/// ```no_run
/// use stegoeggo::{process_image_bytes, ProtectionContext, ProtectionLevel};
///
/// let img_bytes: Vec<u8> = std::fs::read("input.png").unwrap();
/// let ctx = ProtectionContext::new(0.5, 42);
/// let protected = process_image_bytes(&img_bytes, ProtectionLevel::Standard, &ctx).unwrap();
/// std::fs::write("output.png", &protected).unwrap();
/// ```
///
/// # Errors
///
/// Returns [`Error::InvalidFormat`] if the image format cannot be determined
/// for `Light` or `Standard` protection.
/// Returns [`Error::ImageDecode`], [`Error::ImageEncode`], or
/// [`Error::Steganography`] if processing fails.
#[must_use = "the protected image bytes should be saved or used"]
pub fn process_image_bytes(
    img_bytes: &[u8],
    level: ProtectionLevel,
    ctx: &ProtectionContext,
) -> Result<Vec<u8>> {
    if level == ProtectionLevel::Disabled {
        return Ok(img_bytes.to_vec());
    }
    ctx.validate()?;
    if let Some(meta) = ctx.legal_metadata() {
        meta.validate()?;
    }
    let request = request_from_legacy(level, ctx);
    process_request_bytes(img_bytes, &request)
}

/// Process image bytes with protection level and return warnings about
/// degraded protection.
///
/// Like [`process_image_bytes`], but also returns a [`ProtectionWarning`] if
/// the protection was applied with reduced effectiveness. This is important
/// for legal defense use cases where the caller needs to know the actual
/// protection level applied.
///
/// This compatibility helper returns only the first warning. New reverse-proxy
/// integrations should prefer [`process_image_bytes_with_warnings`] so they can
/// log or enforce every warning emitted for the request.
///
/// # Examples
///
/// ```no_run
/// use stegoeggo::{process_image_bytes_with_info, ProtectionContext, ProtectionLevel};
///
/// let img_bytes: Vec<u8> = std::fs::read("input.jpg").unwrap();
/// let ctx = ProtectionContext::new(0.5, 42);
/// let (protected, warning) = process_image_bytes_with_info(
///     &img_bytes, ProtectionLevel::Standard, &ctx
/// ).unwrap();
/// if let Some(w) = warning {
///     eprintln!("Warning: {}", w);
/// }
/// ```
///
/// # Errors
///
/// Returns [`Error::InvalidFormat`] if the image format cannot be determined.
/// Returns [`Error::ImageDecode`], [`Error::ImageEncode`], or
/// [`Error::Steganography`] if processing fails.
pub fn process_image_bytes_with_info(
    img_bytes: &[u8],
    level: ProtectionLevel,
    ctx: &ProtectionContext,
) -> Result<(Vec<u8>, Option<ProtectionWarning>)> {
    let (bytes, warnings) = process_image_bytes_with_warnings(img_bytes, level, ctx)?;
    let warning = warnings.into_iter().next();
    Ok((bytes, warning))
}

/// Process image bytes with protection level and return all protection warnings.
///
/// Compatibility adapter over the legacy level/context API. Translates once
/// via `request_from_legacy()` into [`ProtectionRequest`] and delegates to the
/// canonical [`process_request_bytes_with_warnings`]. Canonical resolution,
/// routing, capacity handling, and runtime warnings are owned by the request
/// path; only compatibility-only presentation warnings are added here (see
/// below). New code should prefer `process_request_bytes_with_warnings`.
///
/// Compatibility-only warnings retained for 0.x callers:
/// - `MissingMacKey` when a legacy authenticated profile was selected without
///   a MAC key (the canonical request model reports this as `Error::Config`
///   for HMAC channels instead of a profile-driven warning).
/// - `ContradictoryLegalClaims` when `inject_legal_claims(false)` is combined
///   with non-empty legal metadata (the canonical request has no disable flag;
///   presence of legal metadata means include). The CLI rejects the same
///   combination as `EXIT_CONFIG` 2.
/// - `JpegReencodeFragile` for non-`Disabled` JPEG output (advisory fragility
///   note; the canonical path reports only resolution and runtime warnings).
///
/// `MetadataInjectionDisabled` and capacity warnings (`LsbCapacitySkipped`,
/// `DctCapacityInsufficient`, `ProgressiveJpegFallback`) come from the
/// canonical path and are not duplicated here. Compatibility warnings are
/// prepended before canonical warnings to preserve 0.x
/// `process_image_bytes_with_info` first-warning ordering.
///
/// # Errors
///
/// Returns [`Error::InvalidFormat`] if the image format cannot be determined.
/// Returns [`Error::ImageDecode`], [`Error::ImageEncode`], or
/// [`Error::Steganography`] if processing fails.
#[allow(deprecated)]
pub fn process_image_bytes_with_warnings(
    img_bytes: &[u8],
    level: ProtectionLevel,
    ctx: &ProtectionContext,
) -> Result<(Vec<u8>, Vec<ProtectionWarning>)> {
    if level == ProtectionLevel::Disabled {
        return Ok((img_bytes.to_vec(), Vec::new()));
    }

    ctx.validate()?;
    if let Some(meta) = ctx.legal_metadata() {
        meta.validate()?;
    }

    let request = request_from_legacy(level, ctx);
    let (bytes, canonical_warnings) = process_request_bytes_with_warnings(img_bytes, &request)?;

    let mut compat = Vec::new();
    if ctx.mac_key().is_none()
        && matches!(
            ctx.evidence_profile(),
            EvidenceProfile::AuthenticatedProvenance | EvidenceProfile::Maximal
        )
    {
        compat.push(ProtectionWarning::MissingMacKey);
    }
    if matches!(ctx.inject_legal_claims(), Some(false))
        && ctx.legal_metadata().is_some_and(|m| m.has_content())
    {
        compat.push(ProtectionWarning::ContradictoryLegalClaims);
    }
    if ImageOutputFormat::is_jpeg(&bytes) {
        compat.push(ProtectionWarning::JpegReencodeFragile);
    }

    let mut warnings = Vec::with_capacity(compat.len() + canonical_warnings.len());
    for w in compat.into_iter().chain(canonical_warnings) {
        if !warnings.contains(&w) {
            warnings.push(w);
        }
    }

    Ok((bytes, warnings))
}

/// Process image bytes using a [`ProtectionRequest`].
///
/// This is the canonical request-based API. It resolves the request into
/// an execution plan, then processes the image according to that plan.
/// Metadata-only requests produce same-format output without pixel decode.
///
/// # Errors
///
/// Returns [`Error::InvalidFormat`] if the image format cannot be determined.
/// Returns config errors if the request contains invalid combinations.
pub fn process_request_bytes(img_bytes: &[u8], request: &ProtectionRequest) -> Result<Vec<u8>> {
    request
        .resource_limits()
        .cloned()
        .unwrap_or_default()
        .check_input_size(img_bytes.len())?;
    let input_format = ImageOutputFormat::from_magic_bytes(img_bytes)
        .ok_or_else(|| Error::InvalidFormat("Unrecognized image format".to_string()))?;

    let plan = resolve_request(request, input_format)?;

    if let Some(meta) = plan.legal_metadata() {
        meta.validate()?;
    }

    let mut budget =
        crate::resource_limits::OperationObserver::new(plan.resource_limits(), img_bytes.len());
    pipeline::process_plan_bytes(img_bytes, &plan, &mut budget).map(|r| r.bytes)
}

/// Process image bytes using a [`ProtectionRequest`], returning warnings.
///
/// Like [`process_request_bytes`], but also returns any warnings about
/// degraded protection conditions.
pub fn process_request_bytes_with_warnings(
    img_bytes: &[u8],
    request: &ProtectionRequest,
) -> Result<(Vec<u8>, Vec<ProtectionWarning>)> {
    request
        .resource_limits()
        .cloned()
        .unwrap_or_default()
        .check_input_size(img_bytes.len())?;
    let input_format = ImageOutputFormat::from_magic_bytes(img_bytes)
        .ok_or_else(|| Error::InvalidFormat("Unrecognized image format".to_string()))?;

    let plan = resolve_request(request, input_format)?;

    if let Some(meta) = plan.legal_metadata() {
        meta.validate()?;
    }

    let mut all_warnings = plan.warnings().to_vec();

    let mut budget =
        crate::resource_limits::OperationObserver::new(plan.resource_limits(), img_bytes.len());
    let pipeline_result = pipeline::process_plan_bytes(img_bytes, &plan, &mut budget)?;

    if let Some(ref summary) = pipeline_result.embed_summary {
        let runtime = pipeline::warnings_from_embed_outcome(summary);
        for w in runtime {
            if !all_warnings.contains(&w) {
                all_warnings.push(w);
            }
        }
    }

    Ok((pipeline_result.bytes, all_warnings))
}

/// Process image bytes using a [`ProtectionRequest`], returning a full execution report.
///
/// This is the most informative request-based API. It resolves the request,
/// processes the image, and returns a detailed report of what was executed
/// and any degradation that occurred.
pub fn process_request_bytes_with_report(
    img_bytes: &[u8],
    request: &ProtectionRequest,
) -> Result<(Vec<u8>, ExecutionReport)> {
    request
        .resource_limits()
        .cloned()
        .unwrap_or_default()
        .check_input_size(img_bytes.len())?;
    let input_format = ImageOutputFormat::from_magic_bytes(img_bytes)
        .ok_or_else(|| Error::InvalidFormat("Unrecognized image format".to_string()))?;

    let plan = resolve_request(request, input_format)?;

    if let Some(meta) = plan.legal_metadata() {
        meta.validate()?;
    }

    let mut warnings = plan.warnings().to_vec();
    let output_format = plan.output_format();
    let format_transcoded = input_format != output_format;

    let mut budget =
        crate::resource_limits::OperationObserver::new(plan.resource_limits(), img_bytes.len());

    let pipeline_result = pipeline::process_plan_bytes(img_bytes, &plan, &mut budget)?;
    let result = pipeline_result.bytes;

    let stego_attempted = plan.channels().has_stego();

    let (stego_succeeded, embed_summary) = if stego_attempted {
        match pipeline_result.embed_summary {
            Some(summary) => {
                let runtime = pipeline::warnings_from_embed_outcome(&summary);
                for w in runtime {
                    if !warnings.contains(&w) {
                        warnings.push(w);
                    }
                }
                let succeeded = summary.is_embedded();
                (succeeded, Some(summary))
            }
            None => (false, None),
        }
    } else {
        (false, None)
    };

    let metadata_injected = if plan.channels().rights_metadata {
        protected::metadata_trap::RightsMetadataProtector::new()
            .has_stego_owned_metadata(&result, output_format)
    } else {
        false
    };

    budget.observe_alloc(result.len());
    let resource_usage = budget.finish(result.len());

    let report = ExecutionReport {
        effective_policy: plan.effective_policy(),
        effective_dmi: plan.effective_dmi(),
        metadata_injected,
        stego_attempted,
        stego_succeeded,
        format_transcoded,
        warnings,
        resource_usage: Some(resource_usage),
        embed_summary,
    };

    Ok((result, report))
}

/// Verify that image bytes contain a protection payload whose integrity can be proved.
///
/// Compatibility projection of the canonical [`VerificationReport`] (see
/// [`verify_image_bytes_report`]). Reports hidden-marker integrity only;
/// use `summary_status` on the report for rights-fallback semantics.
/// Stable and not deprecated.
///
/// # Returns
///
/// - [`VerificationStatus::Verified`] — protection data found and verification passed
/// - [`VerificationStatus::Invalid`] — protection data found but verification failed
///   (corrupted, malformed, unsupported version, missing/failed auth, or resource exhaustion)
/// - [`VerificationStatus::NotFound`] — no protection data found in the image
///
/// # Arguments
///
/// * `img_bytes` - Raw image bytes (PNG, JPEG, or WebP)
/// * `mac_key` - Optional MAC key for HMAC-SHA256 verification. Pass empty slice
///   for checksum-only verification.
///
/// # Examples
///
/// ```no_run
/// # let img_bytes: Vec<u8> = Vec::new();
/// match stegoeggo::verify_image_bytes(&img_bytes, &[]) {
///     stegoeggo::VerificationStatus::Verified => println!("Protected and verified"),
///     stegoeggo::VerificationStatus::Invalid => println!("Protected but verification failed"),
///     stegoeggo::VerificationStatus::NotFound => println!("No protection found"),
/// }
/// ```
pub fn verify_image_bytes(img_bytes: &[u8], mac_key: &[u8]) -> VerificationStatus {
    let facts = crate::verification::canonical::verify_canonical(img_bytes, mac_key);
    crate::verification::canonical::project_status_from_canonical(&facts)
}

